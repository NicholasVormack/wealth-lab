/**
 * WEALTH LAB — A/B Test Generator
 * Generates A/B test variants for headlines, CTAs, and email subject lines.
 * Run with: node scripts/ab-test-generator.mjs
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const LAB = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const HISTORY_PATH = path.join(LAB, "history.log");

function log(message) {
  const ts = new Date().toISOString();
  const line = `[${ts}] ${message}\n`;
  fs.appendFileSync(HISTORY_PATH, line);
  process.stdout.write(line);
}

function run() {
  log("=== A/B TEST GENERATOR RUN ===");

  const tests = [
    {
      name: "Headline A/B Test",
      control: "Free Side Hustle Calculator | Wealth Lab",
      variants: [
        "Calculate Your Side Hustle Profit in 30 Seconds",
        "Free Side Hustle ROI Calculator — No Signup Required",
        "Estimate Monthly Side Hustle Income (Free Tool)",
      ],
      metric: "Click-through rate",
      sampleSize: "1,000 visitors per variant",
      duration: "7–14 days",
    },
    {
      name: "CTA Button A/B Test",
      control: "Calculate Now",
      variants: ["Get My Free Calculation", "Start Calculating", "See My Profit"],
      metric: "Button click rate",
      sampleSize: "500 clicks per variant",
      duration: "3–7 days",
    },
    {
      name: "Email Subject Line A/B Test",
      control: "Your free calculator is here",
      variants: [
        "Open this for your free side hustle tool",
        "⚡ Side hustle profit calculator (free)",
        "I built this for you — free calculator inside",
      ],
      metric: "Open rate",
      sampleSize: "500 subscribers per variant",
      duration: "3–5 days",
    },
  ];

  let output = "# A/B Test Variants\n\n";
  output += "Generated by Wealth Lab A/B Test Generator\n\n";

  tests.forEach((test, i) => {
    output += `## Test ${i + 1}: ${test.name}\n`;
    output += `**Metric:** ${test.metric}\n`;
    output += `**Sample size:** ${test.sampleSize}\n`;
    output += `**Duration:** ${test.duration}\n\n`;
    output += `| Variant | Version |\n|---------|---------|\n`;
    output += `| Control | ${test.control} |\n`;
    test.variants.forEach((v, j) => {
      output += `| Variant B${j + 1} | ${v} |\n`;
    });
    output += "\n";
  });

  output += `## How to Run A/B Tests (Free)

1. **Pick one element to test** — headline, CTA, or subject line
2. **Create 2–4 variants** using the table above
3. **Split traffic evenly** — show variant A to 50% of visitors, variant B to the other 50%
4. **Run for 7–14 days** — don't stop early, even if one variant looks like it's winning
5. **Measure the right metric** — CTR for headlines, click rate for buttons, open rate for subject lines
6. **Deploy the winner** — use the winning variant everywhere
7. **Test again** — never stop optimizing

## Free A/B Testing Tools

- **Google Optimize** (free, sunsetting soon — use alternatives)
- **Manual split** — show different versions on different days of the week
- **Email platform A/B** — Mailchimp and MailerLite free tiers include subject line A/B testing
- **GitHub Pages + JavaScript** — serve different HTML files to different visitors (simple split)
`;

  const outPath = path.join(LAB, "output", "ab-test-variants.md");
  fs.writeFileSync(outPath, output);
  log(`A/B test variants written to ${outPath}`);
  log(`Generated ${tests.length} A/B test frameworks`);
  log("=== A/B TEST GENERATOR COMPLETE ===");
}

run();
